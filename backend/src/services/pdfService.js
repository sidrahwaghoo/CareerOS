const PDFDocument = require('pdfkit');

/**
 * PDF Service - Generate ATS-optimized resume PDF
 */
class PDFService {
  async generateResume(draftContent, record) {
    const doc = new PDFDocument({
      size: 'LETTER',
      margin: { top: 50, bottom: 50, left: 60, right: 60 },
      font: 'Helvetica',
    });

    const buffers = [];
    doc.on('data', (chunk) => buffers.push(chunk));
    const done = new Promise((resolve, reject) => {
      doc.on('end', () => resolve(Buffer.concat(buffers)));
      doc.on('error', reject);
    });

    const pi = record.personalInfo || {};
    // Header
    doc.fontSize(20).font('Helvetica-Bold').fillColor('#171717');
    doc.text(pi.name || 'Your Name');
    doc.fontSize(10).font('Helvetica').fillColor('#404040');
    doc.text(`${pi.headline || 'Professional'}  |  ${pi.location || ''}`);
    const contact = [pi.email, pi.phone, pi.linkedin, pi.portfolio].filter(Boolean);
    if (contact.length) doc.text(contact.join('  |  '));
    doc.moveDown(0.5);

    const sectionTitle = (title) => {
      doc.fontSize(12).font('Helvetica-Bold').fillColor('#171717');
      doc.text(title);
      doc.moveDown(0.2);
    };

    // Professional Summary
    sectionTitle('PROFESSIONAL SUMMARY');
    doc.fontSize(10).font('Helvetica').fillColor('#171717');
    doc.text(draftContent.summary || '');
    doc.moveDown(0.5);

    // Experience
    sectionTitle('EXPERIENCE');
    const experiences = draftContent.experience || record.experience || [];
    experiences.forEach((exp, index) => {
      if (index > 0) doc.moveDown(0.3);
      doc.fontSize(10).font('Helvetica-Bold').fillColor('#171717');
      doc.text(`${exp.role || 'Position'} — ${exp.company || 'Company'}`);
      doc.fontSize(9).font('Helvetica').fillColor('#404040');
      doc.text(`${exp.startDate || ''} ${exp.endDate ? '– ' + exp.endDate : '– Present'}`);
      (exp.achievements || []).forEach((ach) => {
        const text = typeof ach === 'string' ? ach : ach.text;
        doc.fontSize(9).font('Helvetica').fillColor('#171717');
        doc.text(`• ${text}`, { indent: 10, lineGap: 1 });
      });
    });
    doc.moveDown(0.5);

    // Projects
    if (record.projects && record.projects.length) {
      sectionTitle('PROJECTS');
      record.projects.forEach((proj, index) => {
        if (index > 0) doc.moveDown(0.3);
        doc.fontSize(10).font('Helvetica-Bold').fillColor('#171717');
        doc.text(`${proj.name || 'Project'}${proj.role ? ' — ' + proj.role : ''}`);
        if (proj.description) {
          doc.fontSize(9).font('Helvetica').fillColor('#171717');
          doc.text(proj.description, { indent: 10, lineGap: 1 });
        }
        if (proj.techStack && proj.techStack.length) {
          doc.fontSize(9).font('Helvetica').fillColor('#404040');
          doc.text(`Tech: ${proj.techStack.join(', ')}`, { indent: 10 });
        }
      });
      doc.moveDown(0.5);
    }

    // Education
    if (record.education && record.education.length) {
      sectionTitle('EDUCATION');
      record.education.forEach((edu, index) => {
        if (index > 0) doc.moveDown(0.3);
        doc.fontSize(10).font('Helvetica-Bold').fillColor('#171717');
        doc.text(`${edu.degree || 'Degree'} — ${edu.institution || 'Institution'}`);
        doc.fontSize(9).font('Helvetica').fillColor('#404040');
        doc.text(`${edu.startDate || ''} ${edu.endDate ? '– ' + edu.endDate : ''} ${edu.honors || ''}`.trim());
      });
      doc.moveDown(0.5);
    }

    // Skills
    sectionTitle('SKILLS');
    doc.fontSize(9).font('Helvetica').fillColor('#171717');
    const skills = draftContent.skills || record.skills || [];
    if (Array.isArray(skills)) {
      const names = skills.map((s) => (typeof s === 'string' ? s : s.name)).filter(Boolean);
      doc.text(names.join(', '));
    } else {
      doc.text(String(skills));
    }

    doc.moveDown(1);
    doc.fontSize(8).font('Helvetica').fillColor('#404040');
    doc.text('Generated by Credensa — Agentic Career Intelligence', { align: 'center' });
    doc.text('ATS-Optimized Resume', { align: 'center' });

    doc.end();
    return done;
  }
}

module.exports = { PDFService };
